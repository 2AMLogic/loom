//! `loom-daemon verify-output-decl <OUTPUT-PATH> --producer <PATH:L>` —
//! verify a proposal's generated-output declaration (#15387).
//!
//! # Why this exists
//!
//! `defaults/scripts/verify-proposal-refs.sh` checks every cited path
//! against `origin/main` and records a `MISSING FILE` miss for an absent one
//! — which is right for a source citation and wrong for a *generated* one.
//! A proposal's test plan legitimately says "record timings from
//! `build/verification/verify-fast.json` after running make verify-fast",
//! where the report is gitignored and absent from the tree, and only the
//! tracked `Makefile` recipe that produces it (line 270: `--json
//! build/verification/verify-fast.json`) can vouch for the path. Before
//! #15387 the verifier flagged exactly that, and a Champion had to inspect
//! the producer by hand to tell a valid output citation from a broken one.
//!
//! The proposal body declares the producer inline, on one line:
//!
//! ```text
//! `build/verification/verify-fast.json` (generated by `Makefile:270`)
//! ```
//!
//! and the script hands every declared-but-absent path to this subcommand
//! instead of recording the miss itself.
//!
//! # What is checked
//!
//! The producer is read from the PINNED tree at `--rev` (default
//! `origin/main`) via [`super::git_blob_lines::resolved_blob`] — the same
//! symlink-aware reader the line-range check uses — and never executed and
//! never read from the working tree, so a local edit or a locally generated
//! report cannot satisfy the declaration. The cited line must contain the
//! output path as a literal argument or the value of an option such as
//! `--json="build/report.json"`. Quotes may delimit the path. Punctuation
//! and Make expansions appended to a filename stay part of the word.
//!
//! # Exit-code contract
//!
//! | Exit | Meaning | Output |
//! |---|---|---|
//! | `0` | The cited producer line contains the output as a complete argument | (none) |
//! | [`EX_DECL_FAILED`] (1) | Disproof: the producer has no tree entry at the cited path, the cited line does not exist, or it does not pass the output as a complete argument | stdout: `BAD OUTPUT DECL: …` — the caller appends it to its own miss list |
//! | [`EX_USAGE`] (2) | Malformed `--producer` spec, `git` could not be run, or the rev does not resolve | stderr |
//! | [`EX_UNREADABLE`] (10) | The producer entry exists but is unreadable (dangling symlink, unresolved cycle, non-blob) — the declaration could NOT be checked | stderr: `UNREADABLE PRODUCER: …`. **Not a miss**: an unreadable producer is an inconclusive check, not a disproof (#8593's distinction, applied here) |

use std::path::PathBuf;

use anyhow::{Context, Result};

use super::git_blob_lines::{resolved_blob, ResolvedBlob};

/// Disproof: the declaration failed — a miss. Mirrors
/// [`super::git_blob_lines`]'s `EX_OUT_OF_RANGE`.
pub(crate) const EX_DECL_FAILED: i32 = 1;

/// Usage / precondition failure: malformed `--producer`, `git` missing or
/// failed, the rev or workspace does not resolve.
pub(crate) const EX_USAGE: i32 = 2;

/// The producer entry exists but is unreadable — the declaration could not
/// be checked. Inconclusive, not a disproof; the caller must not treat it as
/// a miss. Mirrors [`super::git_blob_lines`]'s `EX_UNREADABLE`.
pub(crate) const EX_UNREADABLE: i32 = 10;

/// `loom-daemon verify-output-decl <OUTPUT-PATH> --producer <PATH:L>
/// [--rev REV] [--workspace DIR] [--cite TEXT]`.
#[derive(clap::Args)]
pub(crate) struct VerifyOutputDeclArgs {
    /// The generated output path cited in the proposal body (it is absent
    /// from the tree — that is why it carries a declaration).
    #[arg(value_name = "OUTPUT-PATH")]
    output: String,

    /// The declared producer citation: `PATH:L`, where line `L` of the
    /// tracked `PATH` at `--rev` must contain the output path as a complete
    /// argument.
    #[arg(long, value_name = "PATH:L")]
    producer: String,

    /// Git rev to read the producer from. The PINNED tree, never the working
    /// tree — a local edit cannot satisfy the declaration.
    #[arg(long, default_value = "origin/main")]
    rev: String,

    /// Repo/workspace root to run `git` in (default: current directory).
    #[arg(long, value_name = "DIR")]
    workspace: Option<PathBuf>,

    /// The citation text to quote in the diagnostic, as the caller's source
    /// actually wrote it (default: the reconstructed declaration).
    #[arg(long, value_name = "TEXT")]
    cite: Option<String>,
}

impl VerifyOutputDeclArgs {
    /// Never returns: exits with the code documented on the module.
    pub(crate) fn run(self) -> Result<()> {
        handle(&self.output, &self.producer, &self.rev, self.workspace, self.cite.as_deref())
    }
}

/// Parse a `PATH:L` producer spec into `(path, line)`. The line number must
/// be all digits and the path non-empty; `rsplit_once` keeps a `:` that is
/// part of the path (none of the verifier's path shapes contain one) on the
/// path side.
pub(crate) fn parse_producer_spec(spec: &str) -> Option<(&str, u64)> {
    let (path, line) = spec.rsplit_once(':')?;
    if path.is_empty() || line.is_empty() || !line.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    let line_no = line.parse::<u64>().ok()?;
    Some((path, line_no))
}

/// A literal shell word may be enclosed in a matching pair of quotes.
fn unquote(word: &str) -> &str {
    for quote in ['\'', '"'] {
        if let Some(inner) = word.strip_prefix(quote).and_then(|w| w.strip_suffix(quote)) {
            return inner;
        }
    }
    word
}

/// Compare whole recipe words without interpreting Make or running the shell.
/// Only unquoted whitespace and shell operators separate words. In particular,
/// `+` and `$(SUFFIX)` after the path are part of the same argument.
pub(crate) fn line_contains_complete_arg(line: &str, needle: &str) -> bool {
    if needle.is_empty() {
        return false;
    }

    let mut quote = None;
    let mut escaped = false;
    let words = line.split(|ch: char| {
        if std::mem::take(&mut escaped) {
            return false;
        }
        if ch == '\\' && quote != Some('\'') {
            escaped = true;
        } else if let Some(open) = quote {
            if ch == open {
                quote = None;
            }
        } else if matches!(ch, '\'' | '"') {
            quote = Some(ch);
        } else {
            return ch.is_ascii_whitespace() || matches!(ch, ';' | '&' | '|' | '<' | '>');
        }
        false
    });

    words.take_while(|word| !word.starts_with('#')).any(|word| {
        let arg = unquote(word);
        if arg == needle {
            return true;
        }
        let Some((option, value)) = arg.split_once('=') else {
            return false;
        };
        // Inside a quoted whole option, any quotes around its value are literal.
        let value = if arg == word { unquote(value) } else { value };
        option.starts_with('-') && value == needle
    })
}

/// 1-based line `line_no` of the content, or `None` when it does not exist.
/// A trailing `\n` produces a final empty segment that is not a line.
pub(crate) fn line_at(content: &[u8], line_no: u64) -> Option<String> {
    if line_no == 0 {
        return None;
    }
    let text = String::from_utf8_lossy(content);
    let segments: Vec<&str> = text.split('\n').collect();
    let real = if content.last() == Some(&b'\n') {
        segments.len().saturating_sub(1)
    } else {
        segments.len()
    };
    let idx = line_no as usize - 1;
    (idx < real).then(|| segments[idx].to_string())
}

/// `wc -l` line count of the content, matching [`resolved_blob`]'s line
/// counting so the diagnostic agrees with `git-blob-lines`' "has only N
/// lines".
fn line_count(content: &[u8]) -> u64 {
    content.iter().filter(|&&b| b == b'\n').count() as u64
}

/// Handle `loom-daemon verify-output-decl …`. Never returns (exits the
/// process with the code documented on the module).
fn handle(
    output: &str,
    producer_spec: &str,
    rev: &str,
    workspace: Option<PathBuf>,
    cite: Option<&str>,
) -> Result<()> {
    let workspace = match workspace {
        Some(w) => w,
        None => std::env::current_dir().context(
            "loom-daemon verify-output-decl: could not resolve the current directory; pass \
             --workspace",
        )?,
    };

    let (producer_path, line_no) = match parse_producer_spec(producer_spec) {
        Some((p, l)) => (p, l),
        None => {
            eprintln!(
                "loom-daemon verify-output-decl: --producer {producer_spec:?} is not a PATH:L \
                 citation"
            );
            std::process::exit(EX_USAGE);
        }
    };

    // The citation as the caller's reader wrote it, so the diagnostic quotes
    // what is actually in the proposal body rather than a path the author
    // never typed. Bare (no backticks of its own): the diagnostics wrap the
    // cite in backticks themselves.
    let cite = cite.map_or_else(
        || format!("{output} (generated by {producer_path}:{line_no})"),
        str::to_string,
    );

    match resolved_blob(&workspace, rev, producer_path) {
        Err(e) => {
            eprintln!("loom-daemon verify-output-decl: {e:#}");
            std::process::exit(EX_USAGE);
        }
        Ok(ResolvedBlob::Absent { .. }) => {
            // stdout, because the caller splices this straight into its own
            // miss list.
            println!(
                "BAD OUTPUT DECL: `{cite}` — producer `{producer_path}` does not exist on {rev}"
            );
            std::process::exit(EX_DECL_FAILED);
        }
        Ok(ResolvedBlob::Unreadable { resolved_path }) => {
            // stderr, because this is NOT a miss — the check could not be
            // performed at all, and an inconclusive check must never block
            // filing the way a disproof does.
            eprintln!(
                "  ! UNREADABLE PRODUCER: `{cite}` — {rev}:{resolved_path} is unreadable \
                 (dangling symlink, unresolved link cycle, or not a regular file); the \
                 declaration was NOT checked — inconclusive, not a miss"
            );
            std::process::exit(EX_UNREADABLE);
        }
        Ok(ResolvedBlob::Content {
            resolved_path,
            bytes,
        }) => {
            let Some(producer_line) = line_at(&bytes, line_no) else {
                println!(
                    "BAD OUTPUT DECL: `{cite}` — {rev}:{resolved_path} has only {} lines, no \
                     line {line_no}",
                    line_count(&bytes)
                );
                std::process::exit(EX_DECL_FAILED);
            };
            if line_contains_complete_arg(&producer_line, output) {
                std::process::exit(0);
            }
            println!(
                "BAD OUTPUT DECL: `{cite}` — {rev}:{resolved_path}:{line_no} does not pass \
                 `{output}` as a complete argument"
            );
            std::process::exit(EX_DECL_FAILED);
        }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn complete_argument_matches_the_downstream_recipe_line() {
        let line = "\t@$(RUN) --timeout 600 --json build/verification/verify-fast.json \\";
        assert!(line_contains_complete_arg(line, "build/verification/verify-fast.json"));
    }

    #[test]
    fn a_prefix_of_the_real_filename_is_not_a_complete_argument() {
        let line = "\t@$(RUN) --json build/verification/verify-fast.json \\";
        assert!(!line_contains_complete_arg(line, "build/verification/verify-fast.jso"));
    }

    #[test]
    fn a_token_continuing_past_the_needle_is_not_a_complete_argument() {
        let line = "\t@$(RUN) --json build/verification/verify-fast.json.bak \\";
        assert!(!line_contains_complete_arg(line, "build/verification/verify-fast.json"));
    }

    #[test]
    fn punctuation_and_make_expansions_can_extend_the_same_argument() {
        for argument in [
            "build/report.json+debug",
            "build/report.json$(SUFFIX)",
            "'build/report.json'+debug",
            "--json=\"build/report.json\"$(SUFFIX)",
            "\"a single argument containing build/report.json inside\"",
            "\"--json='build/report.json'\"",
            "tool # build/report.json",
            r"build/report.json\ suffix",
        ] {
            assert!(!line_contains_complete_arg(argument, "build/report.json"), "{argument}");
        }
        assert!(line_contains_complete_arg("--json='build/report.json'", "build/report.json"));
        assert!(line_contains_complete_arg("\"--json=build/report.json\";", "build/report.json"));
    }

    #[test]
    fn a_token_starting_before_the_needle_is_not_a_complete_argument() {
        let line = "\t@$(RUN) --json mybuild/verification/verify-fast.json \\";
        assert!(!line_contains_complete_arg(line, "build/verification/verify-fast.json"));
    }

    #[test]
    fn quoted_and_equals_separated_arguments_count_as_complete() {
        let quoted = "\t@$(RUN) --json \"build/verification/verify-fast.json\" \\";
        assert!(line_contains_complete_arg(quoted, "build/verification/verify-fast.json"));
        let equals = "\t@$(RUN) --json=build/verification/verify-fast.json \\";
        assert!(line_contains_complete_arg(equals, "build/verification/verify-fast.json"));
    }

    #[test]
    fn a_missing_needle_is_not_a_complete_argument() {
        let line = "\t@echo hi";
        assert!(!line_contains_complete_arg(line, "build/verification/verify-fast.json"));
        assert!(!line_contains_complete_arg(line, ""));
    }

    #[test]
    fn producer_spec_parsing() {
        assert_eq!(parse_producer_spec("Makefile:270"), Some(("Makefile", 270)));
        assert_eq!(parse_producer_spec("tools/Makefile:12"), Some(("tools/Makefile", 12)));
        assert_eq!(parse_producer_spec("Makefile"), None);
        assert_eq!(parse_producer_spec("Makefile:"), None);
        assert_eq!(parse_producer_spec("Makefile:x"), None);
        assert_eq!(parse_producer_spec(":5"), None);
    }

    #[test]
    fn line_at_is_one_based_and_ignores_the_trailing_newline_segment() {
        assert_eq!(line_at(b"one\ntwo\n", 1).as_deref(), Some("one"));
        assert_eq!(line_at(b"one\ntwo\n", 2).as_deref(), Some("two"));
        assert_eq!(line_at(b"one\ntwo\n", 3), None);
        // No trailing newline: the last segment is still a real line.
        assert_eq!(line_at(b"one\ntwo", 2).as_deref(), Some("two"));
        assert_eq!(line_at(b"one\ntwo", 3), None);
        assert_eq!(line_at(b"one\ntwo", 0), None);
    }
}
